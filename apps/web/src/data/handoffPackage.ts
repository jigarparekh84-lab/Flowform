/** Semver-ish schema id for planning-system intake. */
export const HANDOFF_SCHEMA_VERSION = 'flowform.handoff.v1'

/**
 * Embedded README for consumers (Ritara / S&OP / APS).
 * Explains fields without copying proprietary planning schemas.
 */
export const HANDOFF_PACKAGE_README = `# Flowform handoff package (${HANDOFF_SCHEMA_VERSION})

Design-exit payload from Flowform (network / footprint studio) toward a
planning system (e.g. Ritara APS). Contract stub only — not a live API sync.

## Top-level fields

| Field | Purpose |
|-------|---------|
| \`schema_version\` | Package contract id (\`${HANDOFF_SCHEMA_VERSION}\`) |
| \`product\` | Always \`Flowform\` |
| \`target\` | Intended consumer label (Ritara APS intake) |
| \`readme\` | This document (inline) |
| \`meta\` | Project, horizon, timestamps |
| \`brief\` | Decision Brief recommendation + assumptions + notes |
| \`network.sites\` | Nodes (plants, DCs, demand, suppliers, candidates) |
| \`network.lanes\` | Transport lanes (mode, cost, lead, CO₂) |
| \`network.demand_volume\` | Demand volume by site id |
| \`preferred_lanes\` | Demand-inbound / territory-preferred corridors |
| \`territory\` | Soft coverage assignments + metrics (distance default) |
| \`capex_events\` | Multi-year CapEx open/close/expand events |
| \`capex_year_slices\` | Cumulative CapEx / capacity by year |
| \`product_mix\` | Commodity / product groups + demand shares + caps |
| \`bom\` | FG←RM rows + implied RM demand + echelon rollup |
| \`inventory_targets\` | Safety-stock policy rollup (if policies present) |
| \`scenarios\` | Recommended + compared scenario metadata / KPIs |

## Ritara-friendly aliases

Flowform uses planning-friendly names (\`sites\`, \`lanes\`, \`preferred_lanes\`,
\`capex_events\`, \`product_mix\`, \`bom.implied_rm\`, \`inventory_targets\`) so an
intake adapter can map without proprietary source. No Ritara code is embedded.

## Usage

1. Download JSON from Handoff room.
2. Map \`sites\` / \`lanes\` into the planning network master.
3. Apply \`preferred_lanes\` as service territory defaults.
4. Schedule \`capex_events\` on the CapEx / capacity calendar.
5. Seed product mix, BOM implied RM, and inventory targets into S&OP.
`

