export type BuildHandoffArgs = {
  brief: BriefState
  scenarios: Scenario[]
  network: UploadedNetwork
  projectName: string
  horizon: string
  capexRoadmap: CapexRoadmapState
  productMix: ProductMixState
  bom: BomState
  inventoryPolicies: InventoryPolicyState | null
  /** ISO sent timestamp override (defaults to brief.sentToHandoffAt). */
  sentAt?: string | null
  generatedAt?: string
}

function siteFromNode(n: NetworkNode): HandoffSite {
  return {
    site_id: n.id,
    name: n.name,
    kind: n.kind,
    region: n.region,
    capacity: n.capacity,
    lat: n.lat ?? null,
    lng: n.lng ?? null,
    canvas_x: n.x,
    canvas_y: n.y,
  }
}

function laneFlags(
  lane: NetworkLane,
  demandIds: Set<string>,
): Pick<HandoffLane, 'preferred_demand' | 'territory_sourced'> {
  return {
    preferred_demand: demandIds.has(lane.to),
    territory_sourced: lane.id.startsWith('terr-'),
  }
}

function laneFromNetwork(
  lane: NetworkLane,
  demandIds: Set<string>,
): HandoffLane {
  return {
    lane_id: lane.id,
    from_site_id: lane.from,
    to_site_id: lane.to,
    mode: lane.mode,
    cost_per_unit: lane.costPerUnit,
    lead_days: lane.leadDays,
    co2_kg: lane.co2Kg,
    ...laneFlags(lane, demandIds),
  }
}

function scenarioRole(
  id: string,
  brief: BriefState,
  baselineId: string,
): HandoffScenarioMeta['role'] {
  if (id === brief.recommendedScenarioId) return 'recommended'
  if (brief.comparedIds.includes(id)) return 'compared'
  if (id === baselineId) return 'reference'
  return 'other'
}

/** Build enriched S&OP / Ritara handoff package from Flowform state. */
export function buildHandoffPackage(args: BuildHandoffArgs): HandoffPackage {
  const {
    brief,
    scenarios,
    network,
    projectName,
    horizon,
    capexRoadmap,
    productMix,
    bom,
    inventoryPolicies,
  } = args

  const generatedAt = args.generatedAt ?? new Date().toISOString()
  const sentAt =
    args.sentAt !== undefined ? args.sentAt : brief.sentToHandoffAt

  const demandIds = new Set(
    network.nodes.filter((n) => n.kind === 'demand').map((n) => n.id),
  )
  const nodeById = new Map(network.nodes.map((n) => [n.id, n]))

  const sites = network.nodes.map(siteFromNode)
  const lanes = network.lanes.map((l) => laneFromNetwork(l, demandIds))

  const preferredFromNetwork: HandoffPreferredLane[] = network.lanes
    .filter((l) => demandIds.has(l.to) || l.id.startsWith('terr-'))
    .map((l) => {
      const base = laneFromNetwork(l, demandIds)
      return {
        ...base,
        from_name: nodeById.get(l.from)?.name ?? l.from,
        to_name: nodeById.get(l.to)?.name ?? l.to,
        demand_volume: network.demandVolume[l.to] ?? null,
      }
    })

  const territoryPreview = previewTerritory(network, {
    facilityIds: suggestServingIds(network.nodes),
    mode: 'distance',
    coverageMiles: 400,
    coverageLeadDays: 3,
    replaceDemandLanes: false,
    laneMode: 'Truck',
  })

  // Prefer applied network demand-inbound lanes; fall back to territory preview.
  let preferred_lanes = preferredFromNetwork
  if (preferred_lanes.length === 0 && territoryPreview.newLanes.length > 0) {
    preferred_lanes = territoryPreview.newLanes.map((l) => {
      const base = laneFromNetwork(l, demandIds)
      return {
        ...base,
        preferred_demand: true,
        territory_sourced: true,
        from_name: nodeById.get(l.from)?.name ?? l.from,
        to_name: nodeById.get(l.to)?.name ?? l.to,
        demand_volume: network.demandVolume[l.to] ?? null,
      }
    })
  }

  const yearSlices: YearSliceSummary[] = roadmapYearSummaries(
    capexRoadmap,
    network,
  )
  const capex_events = [...capexRoadmap.events]
    .sort((a, b) => a.year - b.year || a.name.localeCompare(b.name))
    .map((e) => ({
      event_id: e.id,
      name: e.name,
      kind: e.kind,
      year_index: e.year,
      year_label: yearLabelFor(capexRoadmap.baseYearLabel, e.year),
      site_id: e.nodeId,
      site_name: e.nodeName,
      capex_m: e.capexM,
      capacity_delta: e.capacityDelta,
      region: e.region,
      facility_kind: e.facilityKind,
      notes: e.notes,
    }))

  const capex_year_slices = yearSlices.map((s) => ({
    year_index: s.year,
    label: s.label,
    year_label: s.yearLabel,
    capex_this_year_m: s.capexThisYearM,
    cumulative_capex_m: s.cumulativeCapexM,
    capacity_delta_this_year: s.capacityDeltaThisYear,
    cumulative_capacity_delta: s.cumulativeCapacityDelta,
    total_capacity_units: s.totalCapacityUnits,
    open_facility_count: s.openFacilityCount,
    event_count: s.eventsThisYear.length,
  }))

  const baseline = scenarios.find((s) => s.id === 'baseline') ?? scenarios[0]
  const rec =
    scenarios.find((s) => s.id === brief.recommendedScenarioId) ?? baseline
  const productRollup = rollupByProductGroup(
    productMix,
    network,
    rec?.kpis ?? baseline.kpis,
  )

  const implied_rm = deriveImpliedRmDemand(bom, network)
  const bom_rollup = bomRollup(bom, network)

  let inventory_targets: HandoffPackage['inventory_targets'] = null
  if (inventoryPolicies && inventoryPolicies.nodes.length > 0) {
    const rollup = computeInventoryRollup(inventoryPolicies, network)
    inventory_targets = {
      present: true,
      formula: rollup.formula,
      total_units: rollup.totalUnits,
      total_dollars: rollup.totalDollars,
      total_dollars_m: rollup.totalDollarsM,
      nodes: rollup.nodes.map((n) => ({
        site_id: n.nodeId,
        name: n.name,
        kind: n.kind,
        service_target_pct: n.serviceTargetPct,
        lead_time_days: n.leadTimeDays,
        safety_stock_units: n.safetyStockUnits,
        inventory_dollars: n.inventoryDollars,
        holding_cost_per_unit: n.holdingCostPerUnit,
      })),
    }
  }

  const scenarioIds = new Set<string>()
  if (brief.recommendedScenarioId) scenarioIds.add(brief.recommendedScenarioId)
  for (const id of brief.comparedIds) scenarioIds.add(id)
  if (baseline) scenarioIds.add(baseline.id)
  // Always include active-ish set: recommended, compared, baseline
  const scenarioList = scenarios.filter((s) => scenarioIds.has(s.id))
  const scenariosMeta: HandoffScenarioMeta[] = scenarioList.map((s) => ({
    scenario_id: s.id,
    name: s.name,
    tag: s.tag,
    role: scenarioRole(s.id, brief, baseline?.id ?? 'baseline'),
    kpis: s.kpis,
    base_id: s.baseId,
    optimize: s.optimizeMeta,
    des_lite: s.desLite,
    resilience: s.resilience,
    inventory_rollup: s.inventoryRollup,
  }))

  const checkedAssumptions = brief.assumptions.filter((a) => a.checked)

  const pkg: HandoffPackage = {
    schema_version: HANDOFF_SCHEMA_VERSION,
    product: 'Flowform',
    target: 'Ritara APS (intake contract)',
    readme: HANDOFF_PACKAGE_README,
    meta: {
      project_name: projectName,
      horizon,
      generated_at: generatedAt,
      sent_at: sentAt,
      network_source: network.source,
    },
    brief: {
      recommended_scenario_id: brief.recommendedScenarioId,
      compared_scenario_ids: [...brief.comparedIds],
      assumptions: brief.assumptions.map((a) => ({
        id: a.id,
        label: a.label,
        checked: a.checked,
      })),
      notes: brief.notes,
    },
    network: {
      sites,
      lanes,
      demand_volume: { ...network.demandVolume },
      site_count: sites.length,
      lane_count: lanes.length,
    },
    preferred_lanes,
    territory: {
      mode: 'distance',
      coverage_miles: 400,
      coverage_lead_days: 3,
      metrics: territoryPreview.metrics,
      assignments: territoryPreview.assignments.map((a) => ({
        demand_id: a.demandId,
        demand_name: a.demandName,
        facility_id: a.facilityId,
        facility_name: a.facilityName,
        miles: a.miles,
        lead_days: a.leadDays,
        volume: a.volume,
        status: a.status,
      })),
      summary: territoryPreview.summary,
    },
    capex_events,
    capex_year_slices,
    product_mix: {
      catalog: productMix.catalog,
      catalog_label: catalogLabel(productMix.catalog),
      groups: productMix.groups,
      demand_mix: productMix.demandMix,
      lane_tags: productMix.laneTags,
      facility_caps: productMix.facilityCaps,
      rollup: productRollup,
    },
    bom: {
      rows: bom.rows,
      fg_shares: bom.fgShares,
      implied_rm,
      rollup: bom_rollup,
    },
    inventory_targets,
    scenarios: scenariosMeta,
    section_counts: {
      sites: sites.length,
      lanes: lanes.length,
      preferred_lanes: preferred_lanes.length,
      territory_assignments: territoryPreview.assignments.length,
      capex_events: capex_events.length,
      product_groups: productMix.groups.length,
      bom_rows: bom.rows.length,
      implied_rm: implied_rm.length,
      inventory_nodes: inventory_targets?.nodes?.length ?? 0,
      scenarios: scenariosMeta.length,
      checked_assumptions: checkedAssumptions.length,
    },
  }

  return pkg
}

/** Human-readable ops brief (Markdown) for planners receiving the package. */
export function buildHandoffOpsBriefMarkdown(pkg: HandoffPackage): string {
  const lines: string[] = [
    `# Flowform → Ritara ops brief`,
    '',
    `**Schema:** \`${pkg.schema_version}\`  `,
    `**Project:** ${pkg.meta.project_name}  `,
    `**Horizon:** ${pkg.meta.horizon}  `,
    `**Generated:** ${pkg.meta.generated_at}  `,
    pkg.meta.sent_at ? `**Sent to Handoff:** ${pkg.meta.sent_at}  ` : '',
    '',
    '> Design-exit package stub. Map fields into the planning system; do not treat as a live sync.',
    '',
    '## Recommendation',
    '',
  ]

  const rec = pkg.scenarios.find((s) => s.role === 'recommended')
  if (rec) {
    lines.push(
      `**${rec.name}** (\`${rec.scenario_id}\`, ${rec.tag})`,
      '',
      `| KPI | Value |`,
      `|-----|-------|`,
      `| Cost | ${rec.kpis.cost.value} |`,
      `| Service | ${rec.kpis.service.value} |`,
      `| CapEx | ${rec.kpis.capex.value} |`,
      `| CO₂ | ${rec.kpis.co2.value} |`,
      `| Risk | ${rec.kpis.risk.value} |`,
    )
    if (rec.kpis.inventory) {
      lines.push(`| Inventory $ | ${rec.kpis.inventory.value} |`)
    }
  } else {
    lines.push('_No recommended scenario in package._')
  }

  lines.push(
    '',
    '## Network',
    '',
    `- **Sites:** ${pkg.network.site_count}`,
    `- **Lanes:** ${pkg.network.lane_count}`,
    `- **Preferred (demand-inbound) lanes:** ${pkg.preferred_lanes.length}`,
    `- **Source:** ${pkg.meta.network_source}`,
    '',
    '### Sites by kind',
    '',
  )

  const byKind = new Map<string, number>()
  for (const s of pkg.network.sites) {
    byKind.set(s.kind, (byKind.get(s.kind) ?? 0) + 1)
  }
  for (const [kind, n] of [...byKind.entries()].sort()) {
    lines.push(`- ${kind}: ${n}`)
  }

  lines.push(
    '',
    '## Territory / preferred lanes',
    '',
    pkg.territory.summary,
    '',
    `- Coverage within ${pkg.territory.coverage_miles} mi: **${pkg.territory.metrics.pctCoveredWithinMiles}%**`,
    `- Coverage within ${pkg.territory.coverage_lead_days}d lead: **${pkg.territory.metrics.pctCoveredWithinLead}%**`,
    `- Gaps: ${pkg.territory.metrics.gapCount} · Overlaps: ${pkg.territory.metrics.overlapCount}`,
    '',
  )

  if (pkg.preferred_lanes.length) {
    lines.push('| From | To | Mode | Lead d | $/u |', '|------|----|------|--------|-----|')
    for (const l of pkg.preferred_lanes.slice(0, 24)) {
      lines.push(
        `| ${l.from_name} | ${l.to_name} | ${l.mode} | ${l.lead_days} | ${l.cost_per_unit} |`,
      )
    }
    if (pkg.preferred_lanes.length > 24) {
      lines.push(`| … | +${pkg.preferred_lanes.length - 24} more | | | |`)
    }
    lines.push('')
  }

  lines.push('## CapEx roadmap', '')
  if (!pkg.capex_events.length) {
    lines.push('_No CapEx events._', '')
  } else {
    lines.push(
      '| Year | Event | Kind | Site | CapEx $M | Δ capacity |',
      '|------|-------|------|------|----------|------------|',
    )
    for (const e of pkg.capex_events) {
      lines.push(
        `| ${e.year_label} (Y${e.year_index}) | ${e.name} | ${e.kind} | ${e.site_name} | ${e.capex_m} | ${e.capacity_delta} |`,
      )
    }
    lines.push('', '### Cumulative by year', '')
    for (const y of pkg.capex_year_slices) {
      lines.push(
        `- **${y.year_label}** (${y.label}): cum CapEx $${y.cumulative_capex_m}M · capacity ${y.total_capacity_units} · ${y.open_facility_count} open · ${y.event_count} events`,
      )
    }
    lines.push('')
  }

  lines.push(
    '## Product mix',
    '',
    `Catalog: **${pkg.product_mix.catalog_label}** (\`${pkg.product_mix.catalog}\`)`,
    '',
  )
  if (pkg.product_mix.rollup.length) {
    lines.push(
      '| Group | Code | Demand share | Capable sites | Cap units |',
      '|-------|------|--------------|---------------|-----------|',
    )
    for (const g of pkg.product_mix.rollup) {
      lines.push(
        `| ${g.name} | ${g.code} | ${g.demandSharePct}% | ${g.capableFacilities} | ${g.capacityUnits} |`,
      )
    }
    lines.push('')
  }

  lines.push(
    '## BOM / implied RM',
    '',
    `- BOM rows: ${pkg.bom.rollup.bomRows}`,
    `- FG SKUs: ${pkg.bom.rollup.fgCount}`,
    `- Components: ${pkg.bom.rollup.componentCount}`,
    `- Total implied RM qty: ${pkg.bom.rollup.totalRmQty}`,
    `- Plant←Supplier flows: ${pkg.bom.rollup.plantSupplierFlows} (${pkg.bom.rollup.impliedLaneGaps} implied gaps)`,
    '',
  )
  if (pkg.bom.implied_rm.length) {
    lines.push(
      '| Component | Kind | Qty needed | Preferred supplier |',
      '|-----------|------|------------|--------------------|',
    )
    for (const r of pkg.bom.implied_rm.slice(0, 20)) {
      lines.push(
        `| ${r.componentName} | ${r.componentKind} | ${Math.round(r.qtyNeeded)} | ${r.preferredSupplierName ?? '—'} |`,
      )
    }
    lines.push('')
  }

  lines.push('## Inventory targets', '')
  if (!pkg.inventory_targets?.present) {
    lines.push('_No inventory policies in package._', '')
  } else {
    lines.push(
      `- Formula: **${pkg.inventory_targets.formula}**`,
      `- Total SS units: **${pkg.inventory_targets.total_units}**`,
      `- Total inventory $: **$${pkg.inventory_targets.total_dollars_m}M**`,
      '',
    )
    if (pkg.inventory_targets.nodes?.length) {
      lines.push(
        '| Site | Kind | Service % | LT d | SS units | Inv $ |',
        '|------|------|-----------|------|----------|-------|',
      )
      for (const n of pkg.inventory_targets.nodes) {
        lines.push(
          `| ${n.name} | ${n.kind} | ${n.service_target_pct} | ${n.lead_time_days} | ${n.safety_stock_units} | $${n.inventory_dollars} |`,
        )
      }
      lines.push('')
    }
  }

  lines.push('## Assumptions (checked)', '')
  const checked = pkg.brief.assumptions.filter((a) => a.checked)
  if (!checked.length) {
    lines.push('_None checked._', '')
  } else {
    for (const a of checked) lines.push(`- [x] ${a.label}`)
    lines.push('')
  }

  if (pkg.brief.notes.trim()) {
    lines.push('## Notes', '', pkg.brief.notes.trim(), '')
  }

  lines.push(
    '## Scenario metadata',
    '',
    '| Scenario | Role | Tag | Cost | Service | CapEx |',
    '|----------|------|-----|------|---------|-------|',
  )
  for (const s of pkg.scenarios) {
    lines.push(
      `| ${s.name} | ${s.role} | ${s.tag} | ${s.kpis.cost.value} | ${s.kpis.service.value} | ${s.kpis.capex.value} |`,
    )
  }

  lines.push(
    '',
    '---',
    '',
    '_Exported from Flowform Handoff — design only; Ritara runs the plan._',
    '',
    '### Field README (from package)',
    '',
    '```',
    pkg.readme.trim(),
    '```',
    '',
  )

  return lines.filter((l, i, arr) => !(l === '' && arr[i - 1] === '')).join('\n')
}

export function downloadHandoffJson(pkg: HandoffPackage, horizon: string) {
  downloadTextFile(
    `flowform-handoff-${horizon}-${pkg.schema_version}.json`,
    JSON.stringify(pkg, null, 2),
    'application/json;charset=utf-8',
  )
}

export function downloadHandoffOpsBrief(pkg: HandoffPackage, horizon: string) {
  downloadTextFile(
    `flowform-handoff-ops-${horizon}.md`,
    buildHandoffOpsBriefMarkdown(pkg),
    'text/markdown;charset=utf-8',
  )
}
