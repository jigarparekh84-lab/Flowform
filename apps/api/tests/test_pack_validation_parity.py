"""Enterprise-pack validator parity: TypeScript original ↔ Python port.

``flowform_engine.pack_validation`` is a hand-port of
``apps/web/src/data/enterprisePack.ts``. The fixture below is the TypeScript
validator's own output for a set of packs (three real samples plus malformed
cases that lean on JavaScript coercion), generated by::

    cd apps/web && npm run gen:pack-parity

so the API stays in step with the browser without a Node dependency at test time.
Regenerate the fixture only when a validation change is intended and reviewed.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

import pytest

from flowform_engine.pack_validation import validate_enterprise_pack

FIXTURE = Path(__file__).resolve().parent / "fixtures" / "enterprise-pack-parity.json"


def _cases() -> list[dict[str, Any]]:
    return json.loads(FIXTURE.read_text())


CASES = _cases()


def _diff(actual: Any, expected: Any, path: str, out: list[str]) -> None:
    if isinstance(expected, dict):
        if not isinstance(actual, dict):
            out.append(f"{path}: expected object, got {actual!r}")
            return
        for key in expected.keys() | actual.keys():
            if key not in expected:
                out.append(f"{path}.{key}: unexpected key (python={actual[key]!r})")
            elif key not in actual:
                out.append(f"{path}.{key}: missing in python (ts={expected[key]!r})")
            else:
                _diff(actual[key], expected[key], f"{path}.{key}", out)
    elif isinstance(expected, list):
        if not isinstance(actual, list) or len(actual) != len(expected):
            out.append(f"{path}: length {len(actual) if isinstance(actual, list) else '?'} != {len(expected)}")
            return
        for i, (a, e) in enumerate(zip(actual, expected)):
            _diff(a, e, f"{path}[{i}]", out)
    elif actual != expected:
        # Distinguish 1 vs 1.0 and True vs 1, which JSON equality hides.
        if (
            isinstance(actual, (int, float))
            and isinstance(expected, (int, float))
            and not isinstance(actual, bool)
            and not isinstance(expected, bool)
            and float(actual) == float(expected)
        ):
            return
        out.append(f"{path}: python={actual!r} ts={expected!r}")


@pytest.mark.parametrize("case", CASES, ids=[c["name"] for c in CASES])
def test_python_port_matches_typescript(case: dict[str, Any]) -> None:
    actual = validate_enterprise_pack(case["pack"])
    problems: list[str] = []
    _diff(actual, case["scorecard"], "$", problems)
    assert not problems, (
        f"{case['name']} diverges from the TypeScript validator:\n"
        + "\n".join(problems[:25])
    )


def test_fixture_covers_the_samples_and_bad_input() -> None:
    names = {c["name"] for c in CASES}
    assert "sample-stress-200" in names
    assert {"null", "empty-sites", "bom-cycles-and-orphans"} <= names
    # Every case must carry the full scorecard, so the comparison is meaningful.
    assert all("scorecard" in c and "issues" in c["scorecard"] for c in CASES)
